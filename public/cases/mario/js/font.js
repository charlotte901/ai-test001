// 预渲染字符画板(白底,使用时按颜色着色)
const glyphCache = {};
function getGlyph(ch, color) {
  const key = ch + "|" + color;
  if (glyphCache[key]) return glyphCache[key];
  const rows = FONT[ch] || FONT[" "];
  const c = document.createElement("canvas");
  c.width = 8; c.height = 8;
  const g = c.getContext("2d");
  g.fillStyle = color;
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      if (rows[y] & (0x80 >> x)) g.fillRect(x, y, 1, 1);
    }
  }
  glyphCache[key] = c;
  return c;
}

// 在 ctx 上绘制像素文本(对齐 8px 网格风格)
function drawText(ctx, text, x, y, color) {
  color = color || PAL.white;
  for (let i = 0; i < text.length; i++) {
    ctx.drawImage(getGlyph(text[i], color), x + i * 8, y);
  }
}
function textWidth(t) { return t.length * 8; }
